import { readFileSync, writeFileSync } from "node:fs";

const files = ["src/css/tokens/primitive.css", "src/css/tokens/semantic.css"];
const raw = files.map((f) => readFileSync(f, "utf8")).join("\n");

function blocks(selector) {
  const vars = {};
  let found = 0;
  let from = 0;
  for (;;) {
    const i = raw.indexOf(selector + " {", from);
    if (i === -1) break;
    found++;
    const start = raw.indexOf("{", i) + 1;
    const end = raw.indexOf("\n}", start);
    for (const m of raw.slice(start, end).matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
      vars[m[1]] = m[2].trim();
    }
    from = end;
  }
  if (!found) throw new Error("missing block " + selector);
  return vars;
}

const base = blocks(":root");
const light = { ...base, ...blocks(':root[data-theme="light"]') };

function resolve(value, scope, depth = 0) {
  if (depth > 12) throw new Error("var cycle: " + value);
  const m = /^var\((--[a-z0-9-]+)\)$/.exec(value.trim());
  if (!m) return value.trim();
  const next = scope[m[1]];
  if (!next) throw new Error("undefined token " + m[1]);
  return resolve(next, scope, depth + 1);
}

function parse(value) {
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(value);
  if (hex) {
    let h = hex[1];
    if (h.length === 3) h = h.split("").map((c) => c + c).join("");
    return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16), 1];
  }
  const rgba = /^rgba?\(([^)]+)\)$/i.exec(value);
  if (rgba) {
    const p = rgba[1].split(",").map((s) => parseFloat(s.trim()));
    return [p[0], p[1], p[2], p[3] === undefined ? 1 : p[3]];
  }
  return null;
}

function over(fg, bg) {
  const a = fg[3];
  return [
    fg[0] * a + bg[0] * (1 - a),
    fg[1] * a + bg[1] * (1 - a),
    fg[2] * a + bg[2] * (1 - a),
    1
  ];
}

function luminance([r, g, b]) {
  const f = (c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

function ratio(a, b) {
  const l1 = luminance(a);
  const l2 = luminance(b);
  return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
}

function colour(token, scope, backdrop) {
  const c = parse(resolve(`var(${token})`, scope));
  if (!c) throw new Error("unparseable " + token);
  return c[3] === 1 ? c : over(c, backdrop);
}

const TEXT_ON_SURFACE = [
  ["--mpn-fg", "--mpn-bg", 4.5],
  ["--mpn-fg", "--mpn-bg-raised", 4.5],
  ["--mpn-fg", "--mpn-bg-sunken", 4.5],
  ["--mpn-fg", "--mpn-bg-overlay", 4.5],
  ["--mpn-fg-muted", "--mpn-bg", 4.5],
  ["--mpn-fg-muted", "--mpn-bg-raised", 4.5],
  ["--mpn-fg-faint", "--mpn-bg", 3.0],
  ["--mpn-fg-faint", "--mpn-bg-raised", 3.0],
  ["--mpn-accent", "--mpn-bg", 4.5],
  ["--mpn-accent", "--mpn-bg-raised", 4.5],
  ["--mpn-focus", "--mpn-bg", 3.0],
  ["--mpn-border-strong", "--mpn-bg", 3.0],
  ["--mpn-border-strong", "--mpn-bg-raised", 3.0],
  ["--mpn-line", "--mpn-bg-raised", 1.15]
];

const STATES = ["ok", "warn", "danger", "info", "pending", "idle"];

const results = [];
let failures = 0;

for (const [themeName, scope] of [["dark", base], ["light", light]]) {
  const pageBg = parse(resolve("var(--mpn-bg)", scope));

  for (const [fg, bg, min] of TEXT_ON_SURFACE) {
    const bgc = colour(bg, scope, pageBg);
    const fgc = colour(fg, scope, bgc);
    const r = ratio(fgc, bgc);
    const pass = r >= min;
    if (!pass) failures++;
    results.push({ theme: themeName, fg, bg, ratio: r, min, pass });
  }

  for (const s of STATES) {
    const surfaces = [
      ["--mpn-bg", 4.5],
      ["--mpn-bg-raised", 4.5]
    ];
    for (const [bg, min] of surfaces) {
      const bgc = colour(bg, scope, pageBg);
      const tint = colour(`--mpn-${s}-tint`, scope, bgc);
      const fgc = colour(`--mpn-${s}`, scope, tint);
      const r = ratio(fgc, tint);
      const pass = r >= min;
      if (!pass) failures++;
      results.push({ theme: themeName, fg: `--mpn-${s}`, bg: `${s}-tint on ${bg}`, ratio: r, min, pass });
    }
  }

  const accentSolid = colour("--mpn-accent-solid", scope, pageBg);
  const onAccent = colour("--mpn-fg-on-accent", scope, accentSolid);
  const r = ratio(onAccent, accentSolid);
  if (r < 4.5) failures++;
  results.push({
    theme: themeName,
    fg: "--mpn-fg-on-accent",
    bg: "--mpn-accent-solid",
    ratio: r,
    min: 4.5,
    pass: r >= 4.5
  });
}

const rows = results
  .map(
    (r) =>
      `| ${r.theme} | \`${r.fg}\` | \`${r.bg}\` | ${r.ratio.toFixed(2)} | ${r.min.toFixed(1)} | ${r.pass ? "pass" : "**FAIL**"} |`
  )
  .join("\n");

const report = `# Contrast audit

Generated by \`node build/a11y.mjs\`. Every pair is resolved through the token chain and composited
over its real backdrop, so translucent surfaces are measured at the colour they actually render, not
at their declared alpha.

Thresholds: 4.5 for body text (WCAG AA), 3.0 for large text, non-text UI and focus indicators.
Border and divider rows use a lower bar because they carry no information on their own — depth
ordering is what must survive, and that is checked in greyscale instead.

${failures === 0 ? "All " + results.length + " pairs pass." : "**" + failures + " of " + results.length + " pairs fail.**"}

| Theme | Foreground | Background | Ratio | Min | Result |
|---|---|---|---|---|---|
${rows}
`;

writeFileSync("docs/accessibility.md", report);
console.log(`  docs/accessibility.md   ${results.length} pairs, ${failures} failing`);

for (const r of results.filter((x) => !x.pass)) {
  console.log(`    FAIL ${r.theme}  ${r.fg} on ${r.bg}  ${r.ratio.toFixed(2)} < ${r.min}`);
}

if (failures > 0) process.exitCode = 1;
